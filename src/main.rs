/// One job at a time, with a fixed cool-down between jobs. This is the whole
/// traffic-control mechanism: providers only ever see a trickle.
async fn worker_loop(
    mut jobs: mpsc::Receiver<ChatJob>,
    mut shutdown: watch::Receiver<bool>,
    db: DatabaseConnection,
    ai: AiClient,
    system_prompt: String,
    spacing: Duration,
) {
    info!("AI worker started (spacing: {:?})", spacing);

    while let Some(job) = jobs.recv().await {
        let ChatJob {
            user_id,
            message,
            respond_to,
        } = job;

        // A client that timed out or navigated away no longer needs an AI
        // call; skip its queued job instead of spending provider quota.
        if respond_to.is_closed() {
            warn!(user_id = %user_id, "dropping queued AI job: client disconnected");
            continue;
        }

        let result = process_chat_job(&db, &ai, &system_prompt, &user_id, &message).await;

        if respond_to.send(result).is_err() {
            warn!(user_id = %user_id, "client disconnected before the reply was ready");
        }

        // During shutdown, skip the cool-down and drain whatever is already
        // queued. New requests have stopped arriving because the HTTP server
        // has finished its graceful shutdown by this point.
        if *shutdown.borrow() {
            continue;
        }

        tokio::select! {
            _ = tokio::time::sleep(spacing) => {}
            changed = shutdown.changed() => {
                if changed.is_ok() {
                    info!("shutdown requested; draining queued AI jobs without spacing");
                }
            }
        }
    }

    info!("AI worker stopped");
}

/// Replay the guest's full history, ask the AI, then persist both turns.
///
/// Messages are written only after a successful AI reply, inside one
/// transaction, so a failed AI call cannot leave an unanswered question in the
/// transcript.
async fn process_chat_job(
    db: &DatabaseConnection,
    ai: &AiClient,
    system_prompt: &str,
    user_id: &str,
    message: &str,
) -> Result<String, JobError> {
    let history = load_history(db, user_id)
        .await
        .map_err(|err| JobError::Internal(format!("failed to load conversation history: {err}")))?;

    let mut turns = Vec::with_capacity(history.len() + 2);
    turns.push(ChatTurn::new("system", system_prompt));
    for saved in &history {
        if saved.role == "user" || saved.role == "assistant" {
            turns.push(ChatTurn::new(&saved.role, saved.content.clone()));
        }
    }
    turns.push(ChatTurn::new("user", message));

    let ai_reply = ai.call_ai(&turns).await.map_err(JobError::AiUnavailable)?;

    let transaction = db
        .begin()
        .await
        .map_err(|err| JobError::Internal(format!("could not start a transaction: {err}")))?;

    let user_created_at: DateTime<Utc> = Utc::now();
    let assistant_created_at: DateTime<Utc> = Utc::now();

    for (role, content, created_at) in [
        ("user", message.to_string(), user_created_at),
        ("assistant", ai_reply.content.clone(), assistant_created_at),
    ] {
        let active = chat_message::ActiveModel {
            user_id: Set(user_id.to_string()),
            role: Set(role.to_string()),
            content: Set(content),
            created_at: Set(created_at),
            ..Default::default()
        };

        active
            .insert(&transaction)
            .await
            .map_err(|err| JobError::Internal(format!("could not save a chat message: {err}")))?;
    }

    transaction
        .commit()
        .await
        .map_err(|err| JobError::Internal(format!("could not commit the transcript: {err}")))?;

    info!(
        user_id = %user_id,
        provider = ai_reply.provider,
        model = %ai_reply.model,
        chars = ai_reply.content.chars().count(),
        "AI reply delivered"
    );
    Ok(ai_reply.content)
}

