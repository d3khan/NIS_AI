//! School AI chat assistant.
//!
//! A single-binary Axum service that:
//! - serves the vanilla JS chat UI from `static/`,
//! - stores per-guest conversation history in PostgreSQL through SeaORM,
//! - asks a Groq model chain first, then an OpenRouter model chain,
//! - funnels every AI call through one worker that runs at most one request
//!   every few seconds, so provider quotas are never bursted.
//!
//! The service is a standalone Axum server: the host provides `DATABASE_URL`,
//! `PORT`, and the provider API keys through the environment.
//!
//! Guests are identified by a UUID v4 generated by the browser. No accounts,
//! cookies, or sessions are required.

