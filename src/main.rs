fn admin_authorized(headers: &HeaderMap, expected: &str) -> bool {
    use subtle::ConstantTimeEq;

    headers
        .get(header::AUTHORIZATION)
        .and_then(|value| value.to_str().ok())
        .and_then(|value| value.strip_prefix("Bearer "))
        .map(|token| token.trim().as_bytes().ct_eq(expected.as_bytes()).into())
        .unwrap_or(false)
}

fn unauthorized() -> Response {
    (
        StatusCode::UNAUTHORIZED,
        [(header::WWW_AUTHENTICATE, "Bearer")],
        Json(StatusMessage {
            status: "error",
            message: "A valid NEON_ADMIN_TOKEN bearer token is required.".to_string(),
        }),
    )
        .into_response()
}

/// A single diagnostic view of every Neon service wired into the process.
/// Credentials are never included; only configuration and reachability are.
async fn neon_status(State(state): State<AppState>, headers: HeaderMap) -> Response {
    if !admin_authorized(&headers, &state.neon_admin_token) {
        return unauthorized();
    }

    let postgres = match tokio::time::timeout(Duration::from_secs(3), state.db.ping()).await {
        Ok(Ok(())) => json!({ "status": "ok" }),
        Ok(Err(err)) => json!({ "status": "error", "detail": err.to_string() }),
        Err(_) => json!({ "status": "error", "detail": "ping timed out" }),
    };

    let functions = match &state.neon.function_hello_url {
        Some(url) => match state.neon.call_hello_function().await {
            Ok((status, body)) => {
                json!({ "configured": true, "url": url, "http_status": status, "body": body })
            }
            Err(err) => json!({ "configured": true, "url": url, "error": err }),
        },
        None => json!({ "configured": false }),
    };

    let storage = match &state.neon.storage {
        Some(storage) => match storage.head_bucket().await {
            Ok(()) => json!({
                "configured": true,
                "bucket": storage.bucket,
                "endpoint": storage.endpoint,
                "status": "ok"
            }),
            Err(err) => json!({
                "configured": true,
                "bucket": storage.bucket,
                "endpoint": storage.endpoint,
                "status": "error",
                "detail": err
            }),
        },
        None => json!({ "configured": false }),
    };

    Json(json!({
        "status": "ok",
        "postgres": postgres,
        "functions": functions,
        "storage": storage,
        "realtime": state.neon.realtime_summary(),
    }))
    .into_response()
}

