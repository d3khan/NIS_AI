async fn health(State(state): State<AppState>) -> Response {
    if state.jobs.is_closed() {
        error!("health check failed: AI worker queue is closed");
        return api_error(
            StatusCode::SERVICE_UNAVAILABLE,
            "The assistant worker is unavailable.",
        );
    }

    match tokio::time::timeout(Duration::from_secs(3), state.db.ping()).await {
        Ok(Ok(())) => (StatusCode::OK, Json(json!({ "status": "ok" }))).into_response(),
        Ok(Err(err)) => {
            error!(error = %err, "health check failed: database ping failed");
            api_error(
                StatusCode::SERVICE_UNAVAILABLE,
                "The database is unavailable.",
            )
        }
        Err(_) => {
            error!("health check failed: database ping timed out");
            api_error(
                StatusCode::SERVICE_UNAVAILABLE,
                "The database did not respond in time.",
            )
        }
    }
}

async fn chat(
    State(state): State<AppState>,
    payload: Result<Json<ChatRequest>, JsonRejection>,
) -> Response {
    let Json(payload) = match payload {
        Ok(payload) => payload,
        Err(rejection) => {
            warn!(error = %rejection.body_text(), "chat payload rejected");
            return api_error(
                StatusCode::BAD_REQUEST,
                "Invalid request. Please refresh the page and try again.",
            );
        }
    };

    // Normalise the browser-generated UUID so casing can never split history.
    let user_id = match Uuid::parse_str(payload.user_id.trim()) {
        Ok(uuid) => uuid.to_string(),
        Err(_) => {
            warn!("chat request rejected: invalid user id");
            return api_error(
                StatusCode::BAD_REQUEST,
                "Invalid user id. Please refresh the page and try again.",
            );
        }
    };

    let message = payload.message.trim();
    if message.is_empty() {
        warn!(user_id = %user_id, "chat request rejected: empty message");
        return api_error(StatusCode::BAD_REQUEST, "Please type a question first.");
    }
    let message_chars = message.chars().count();
    if message_chars > MAX_MESSAGE_CHARS {
        warn!(
            user_id = %user_id,
            message_chars,
            "chat request rejected: message too long"
        );
        return api_error(
            StatusCode::BAD_REQUEST,
            "That message is a little too long. Please shorten it and try again.",
        );
    }

    info!(
        user_id = %user_id,
        message_chars,
        "chat request accepted"
    );

    let (respond_to, response_rx) = oneshot::channel();
    let job = ChatJob {
        user_id: user_id.clone(),
        message: message.to_string(),
        respond_to,
    };

    match state.jobs.try_send(job) {
        Ok(()) => {}
        Err(mpsc::error::TrySendError::Full(_)) => {
            warn!(
                user_id = %user_id,
                capacity = state.queue_capacity,
                "AI queue full; returning 503"
            );
            return status_message(
                StatusCode::SERVICE_UNAVAILABLE,
                "busy",
                "The assistant is busy right now. Please try again in a moment.",
            );
        }
        Err(mpsc::error::TrySendError::Closed(_)) => {
            error!("AI worker queue is closed; returning 503");
            return status_message(
                StatusCode::SERVICE_UNAVAILABLE,
                "error",
                "The assistant is restarting. Please try again in a moment.",
            );
        }
    }

    match tokio::time::timeout(state.chat_response_timeout, response_rx).await {
        Ok(Ok(Ok(reply))) => (
            StatusCode::OK,
            Json(ChatReply {
                status: "ok",
                reply,
            }),
        )
            .into_response(),
        Ok(Ok(Err(JobError::AiUnavailable(failure)))) => {
            error!(
                user_id = %user_id,
                attempts = failure.attempts.len(),
                "chat request failed: all AI providers unavailable"
            );
            api_error(
                StatusCode::SERVICE_UNAVAILABLE,
                "The school assistant is temporarily unavailable. Please try again in a moment.",
            )
        }
        Ok(Ok(Err(JobError::Internal(detail)))) => {
            error!(user_id = %user_id, error = %detail, "chat job failed");
            api_error(
                StatusCode::INTERNAL_SERVER_ERROR,
                "Something went wrong while preparing the answer. Please try again.",
            )
        }
        Ok(Err(_)) => {
            error!(user_id = %user_id, "chat job response channel closed");
            api_error(
                StatusCode::INTERNAL_SERVER_ERROR,
                "Something went wrong while preparing the answer. Please try again.",
            )
        }
        Err(_) => {
            warn!(
                user_id = %user_id,
                timeout_secs = state.chat_response_timeout.as_secs(),
                "chat response timed out"
            );
            status_message(
                StatusCode::SERVICE_UNAVAILABLE,
                "busy",
                "The assistant is taking longer than expected. Please try again in a moment.",
            )
        }
    }
}

fn api_error(status: StatusCode, message: &str) -> Response {
    status_message(status, "error", message)
}

fn status_message(status: StatusCode, kind: &'static str, message: impl Into<String>) -> Response {
    (
        status,
        Json(StatusMessage {
            status: kind,
            message: message.into(),
        }),
    )
        .into_response()
}

