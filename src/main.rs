async fn storage_put(
    State(state): State<AppState>,
    headers: HeaderMap,
    AxumPath(key): AxumPath<String>,
    body: Bytes,
) -> Response {
    if !admin_authorized(&headers, &state.neon_admin_token) {
        return unauthorized();
    }
    let Some(storage) = &state.neon.storage else {
        return api_error(
            StatusCode::SERVICE_UNAVAILABLE,
            "Object storage is not configured for this branch.",
        );
    };
    if !neon::valid_key(&key) {
        return api_error(
            StatusCode::BAD_REQUEST,
            "The object key contains unsupported characters or segments.",
        );
    }
    if body.len() > MAX_STORAGE_OBJECT_BYTES {
        return api_error(StatusCode::PAYLOAD_TOO_LARGE, "The object exceeds 5 MiB.");
    }

    let content_type = headers
        .get(header::CONTENT_TYPE)
        .and_then(|value| value.to_str().ok())
        .unwrap_or("application/octet-stream");
    if content_type.len() > 128 || content_type.chars().any(char::is_control) {
        return api_error(
            StatusCode::BAD_REQUEST,
            "The Content-Type header is not valid.",
        );
    }

    match storage.put(&key, body.to_vec(), content_type).await {
        Ok(()) => (
            StatusCode::CREATED,
            Json(json!({
                "status": "ok",
                "bucket": storage.bucket,
                "key": key,
                "bytes": body.len(),
                "content_type": content_type,
            })),
        )
            .into_response(),
        Err(err) => {
            error!(error = %err, "object storage upload failed");
            api_error(
                StatusCode::BAD_GATEWAY,
                "Object storage could not store the object.",
            )
        }
    }
}

async fn storage_get(
    State(state): State<AppState>,
    headers: HeaderMap,
    AxumPath(key): AxumPath<String>,
) -> Response {
    if !admin_authorized(&headers, &state.neon_admin_token) {
        return unauthorized();
    }
    let Some(storage) = &state.neon.storage else {
        return api_error(
            StatusCode::SERVICE_UNAVAILABLE,
            "Object storage is not configured for this branch.",
        );
    };
    if !neon::valid_key(&key) {
        return api_error(
            StatusCode::BAD_REQUEST,
            "The object key contains unsupported characters or segments.",
        );
    }

    match storage.get(&key).await {
        Ok((bytes, content_type)) => {
            let mut response = Response::new(axum::body::Body::from(bytes));
            response.headers_mut().insert(
                header::CONTENT_TYPE,
                HeaderValue::from_bytes(content_type.as_bytes())
                    .unwrap_or_else(|_| HeaderValue::from_static("application/octet-stream")),
            );
            response
                .headers_mut()
                .insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
            response
        }
        Err(err) if err == "object not found" => {
            api_error(StatusCode::NOT_FOUND, "That object does not exist.")
        }
        Err(err) => {
            error!(error = %err, "object storage download failed");
            api_error(
                StatusCode::BAD_GATEWAY,
                "Object storage could not read the object.",
            )
        }
    }
}

