struct SchoolKnowledge {
    school_name: String,
    system_prompt: String,
}

fn load_school_knowledge(
    path: &str,
    name_override: Option<&str>,
) -> Result<SchoolKnowledge, String> {
    let contents = std::fs::read_to_string(path).map_err(|err| {
        format!(
            "could not read the school knowledge file '{path}': {err}. \
Set SCHOOL_KNOWLEDGE_PATH to a readable markdown file."
        )
    })?;
    let contents = contents.trim().to_string();
    if contents.is_empty() {
        return Err(format!(
            "the school knowledge file '{path}' is empty. Add the school information before starting."
        ));
    }

    let school_name = name_override
        .map(str::trim)
        .filter(|name| !name.is_empty())
        .map(ToString::to_string)
        .or_else(|| school_name_from_knowledge(&contents))
        .unwrap_or_else(|| "School".to_string());

    let system_prompt = build_system_prompt(&school_name, &contents);
    Ok(SchoolKnowledge {
        school_name,
        system_prompt,
    })
}

fn school_name_from_knowledge(knowledge: &str) -> Option<String> {
    knowledge.lines().find_map(|line| {
        line.strip_prefix("# ")
            .map(str::trim)
            .filter(|heading| !heading.is_empty())
            .map(ToString::to_string)
    })
}

fn build_system_prompt(school_name: &str, school_knowledge: &str) -> String {
    format!(
        "You are the {school_name} Assistant for parents. \
Read the provided school_knowledge.md carefully to answer the user's question. \
Assume the user is a parent unless they explicitly state they are a student. \
Use only the school information below. If the answer is not present, say that you do not know \
and direct the parent to the main office. Be warm, patient, and professional. \
Keep answers clear and concise. Write plain text only: do not use Markdown syntax such as \
**bold**, headings, or tables.\n\
--- BEGIN school_knowledge.md ---\n\
{school_knowledge}\n\
--- END school_knowledge.md ---"
    )
}

async fn shutdown_signal() {
    let ctrl_c = async {
        if let Err(err) = tokio::signal::ctrl_c().await {
            error!(error = %err, "failed to listen for Ctrl+C");
        }
    };

    #[cfg(windows)]
    let ctrl_break = async {
        match tokio::signal::windows::ctrl_break() {
            Ok(mut signal) => {
                signal.recv().await;
            }
            Err(err) => {
                error!(error = %err, "failed to listen for Ctrl+Break");
                std::future::pending::<()>().await;
            }
        }
    };

    #[cfg(not(windows))]
    let ctrl_break = std::future::pending::<()>();

    #[cfg(unix)]
    let terminate = async {
        match tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate()) {
            Ok(mut signal) => {
                signal.recv().await;
            }
            Err(err) => {
                error!(error = %err, "failed to listen for SIGTERM");
                std::future::pending::<()>().await;
            }
        }
    };

    #[cfg(not(unix))]
    let terminate = std::future::pending::<()>();

    tokio::select! {
        _ = ctrl_c => info!("Ctrl+C received"),
        _ = ctrl_break => info!("Ctrl+Break received"),
        _ = terminate => info!("SIGTERM received"),
    }
    info!("shutdown signal received; draining in-flight requests");
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    // `.env` is convenient locally; production injects real environment variables.
    dotenvy::dotenv().ok();

    let config = Config::from_env().unwrap_or_else(|error| {
        panic!("startup configuration error:\n{error}");
    });
    init_tracing(config.log_format);

    if !Path::new("static/index.html").is_file() {
        panic!("static/index.html is missing; the frontend cannot be served");
    }

    info!(
        version = env!("CARGO_PKG_VERSION"),
        port = config.port,
        queue_capacity = config.queue_capacity,
        worker_interval_secs = config.worker_interval.as_secs(),
        ai_attempt_timeout_secs = config.ai_attempt_timeout.as_secs(),
        "starting school chat"
    );

    let knowledge =
        load_school_knowledge(&config.school_knowledge_path, config.school_name.as_deref())
            .unwrap_or_else(|error| {
                error!(error = %error, "school knowledge could not be loaded");
                panic!("school knowledge could not be loaded: {error}");
            });

    let db = match init_database(&config).await {
        Ok(db) => db,
        Err(err) => {
            error!(error = %err, "database initialisation failed");
            panic!("database initialisation failed: {err}");
        }
    };

    let ai = AiClient::new(&config);
    let neon = neon::NeonServices::new(
        config.neon_function_hello_url.clone(),
        config.neon_storage.clone(),
        config.neon_realtime.clone(),
    );
    info!(
        functions = config.neon_function_hello_url.is_some(),
        object_storage = config.neon_storage.is_some(),
        realtime = config.neon_realtime.is_some(),
        "Neon services wired"
    );

    let (jobs_tx, jobs_rx) = mpsc::channel::<ChatJob>(config.queue_capacity);
    let (shutdown_tx, shutdown_rx) = watch::channel(false);
    let mut worker = tokio::spawn(worker_loop(
        jobs_rx,
        shutdown_rx,
        db.clone(),
        ai,
        knowledge.system_prompt,
        config.worker_interval,
    ));

    let state = AppState {
        jobs: jobs_tx,
        db: db.clone(),
        queue_capacity: config.queue_capacity,
        chat_response_timeout: config.chat_response_timeout,
        neon,
        neon_admin_token: config.neon_admin_token.clone(),
    };

    let core_routes = Router::new()
        .route("/chat", post(chat))
        .route("/health", get(health))
        .layer(DefaultBodyLimit::max(16 * 1024));

    let neon_routes = Router::new()
        .route("/neon/status", get(neon_status))
        .route("/neon/functions/hello", get(neon_function_hello))
        .route("/neon/storage/objects", get(storage_list))
        .route(
            "/neon/storage/objects/{*key}",
            get(storage_get).put(storage_put).delete(storage_delete),
        )
        .route("/neon/realtime/sealed", get(realtime_sealed))
        .layer(DefaultBodyLimit::max(MAX_STORAGE_OBJECT_BYTES));

    let app = core_routes
        .merge(neon_routes)
        // Serve the single-page UI; unknown paths fall back to index.html.
        .fallback_service(ServeDir::new("static").fallback(ServeFile::new("static/index.html")))
        .layer(
            TraceLayer::new_for_http()
                .make_span_with(DefaultMakeSpan::new().level(Level::INFO))
                .on_request(DefaultOnRequest::new().level(Level::INFO))
                .on_response(
                    DefaultOnResponse::new()
                        .level(Level::INFO)
                        .latency_unit(LatencyUnit::Millis),
                )
                .on_failure(DefaultOnFailure::new().level(Level::ERROR)),
        )
        .with_state(state);

    let listener = tokio::net::TcpListener::bind(("0.0.0.0", config.port)).await?;
    info!(
        school = %knowledge.school_name,
        port = config.port,
        queue_capacity = config.queue_capacity,
        worker_interval_secs = config.worker_interval.as_secs(),
        "school chat server listening on http://localhost:{}",
        config.port
    );

    let serve_result = axum::serve(listener, app)
        .with_graceful_shutdown(shutdown_signal())
        .await;
    let _ = shutdown_tx.send(true);
    if let Err(err) = &serve_result {
        error!(error = %err, "HTTP server error");
    }

    info!("HTTP server stopped; draining the AI worker");
    match tokio::time::timeout(config.shutdown_timeout, &mut worker).await {
        // The worker logs its own "AI worker stopped" line when it exits.
        Ok(Ok(())) => {}
        Ok(Err(err)) => error!(error = %err, "AI worker task failed"),
        Err(_) => {
            warn!(
                timeout_secs = config.shutdown_timeout.as_secs(),
                "AI worker did not stop in time; aborting"
            );
            worker.abort();
            let _ = worker.await;
        }
    }

    if let Err(err) = db.close_by_ref().await {
        warn!(error = %err, "database pool close failed");
    }
    info!("shutdown complete");
    serve_result?;
    Ok(())
}
