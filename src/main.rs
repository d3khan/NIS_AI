impl AiClient {
    fn new(config: &Config) -> Self {
        let http = reqwest::Client::builder()
            .timeout(config.ai_attempt_timeout)
            .connect_timeout(Duration::from_secs(10))
            .pool_idle_timeout(Duration::from_secs(90))
            .pool_max_idle_per_host(4)
            .redirect(reqwest::redirect::Policy::none())
            .user_agent(concat!("school-chat/", env!("CARGO_PKG_VERSION")))
            .build()
            .expect("failed to build the HTTP client");

        Self {
            http,
            groq: ProviderConfig {
                url: config.groq_url.clone(),
                api_key: config.groq_api_key.clone(),
                headers: Vec::new(),
            },
            openrouter: ProviderConfig {
                url: config.openrouter_url.clone(),
                api_key: config.openrouter_api_key.clone(),
                headers: config.openrouter_headers.clone(),
            },
            groq_models: config.groq_models.clone(),
            openrouter_models: config.openrouter_models.clone(),
        }
    }

    /// Try every Groq model in order, then every OpenRouter model in order.
    /// Any provider error (429, 5xx, timeout, malformed response) moves on.
    async fn call_ai(&self, messages: &[ChatTurn]) -> Result<AiReply, AiFailure> {
        let mut attempts: Vec<String> =
            Vec::with_capacity(self.groq_models.len() + self.openrouter_models.len());

        for (index, model) in self.groq_models.iter().enumerate() {
            let started = Instant::now();
            match call_openai_compatible(&self.http, &self.groq, model, messages).await {
                Ok(content) => {
                    info!(
                        provider = "groq",
                        model = %model,
                        attempt = index + 1,
                        latency_ms = started.elapsed().as_millis() as u64,
                        "AI provider succeeded"
                    );
                    return Ok(AiReply {
                        content,
                        provider: "groq",
                        model: model.clone(),
                    });
                }
                Err(err) => {
                    warn!(
                        provider = "groq",
                        model = %model,
                        attempt = index + 1,
                        latency_ms = started.elapsed().as_millis() as u64,
                        error = %err,
                        "AI provider attempt failed"
                    );
                    attempts.push(format!("groq/{model}: {err}"));
                }
            }
        }

        for (index, model) in self.openrouter_models.iter().enumerate() {
            let started = Instant::now();
            match call_openai_compatible(&self.http, &self.openrouter, model, messages).await {
                Ok(content) => {
                    info!(
                        provider = "openrouter",
                        model = %model,
                        attempt = self.groq_models.len() + index + 1,
                        latency_ms = started.elapsed().as_millis() as u64,
                        "AI provider succeeded"
                    );
                    return Ok(AiReply {
                        content,
                        provider: "openrouter",
                        model: model.clone(),
                    });
                }
                Err(err) => {
                    warn!(
                        provider = "openrouter",
                        model = %model,
                        attempt = self.groq_models.len() + index + 1,
                        latency_ms = started.elapsed().as_millis() as u64,
                        error = %err,
                        "AI provider attempt failed"
                    );
                    attempts.push(format!("openrouter/{model}: {err}"));
                }
            }
        }

        error!(attempts = attempts.len(), "all AI provider attempts failed");
        Err(AiFailure { attempts })
    }
}

/// Send one OpenAI-compatible chat completion request and extract the reply.
async fn call_openai_compatible(
    http: &reqwest::Client,
    provider: &ProviderConfig,
    model: &str,
    messages: &[ChatTurn],
) -> Result<String, String> {
    let body = json!({
        "model": model,
        "messages": messages,
        "temperature": 0.6,
        "max_tokens": MAX_REPLY_TOKENS,
    });

    let mut request = http
        .post(&provider.url)
        .bearer_auth(&provider.api_key)
        .json(&body);
    for (name, value) in &provider.headers {
        request = request.header(*name, value.clone());
    }

    let response = request
        .send()
        .await
        .map_err(|err| format!("request failed: {err}"))?;

    let status = response.status();
    let raw_body = response
        .text()
        .await
        .map_err(|err| format!("could not read response body: {err}"))?;

    if !status.is_success() {
        return Err(format!(
            "HTTP {}: {}",
            status.as_u16(),
            truncate_for_log(&raw_body, 300)
        ));
    }

    let parsed: ChatCompletionResponse = serde_json::from_str(&raw_body)
        .map_err(|err| format!("unexpected response shape: {err}"))?;

    let reply = parsed
        .choices
        .into_iter()
        .next()
        .and_then(|choice| choice.message.content)
        .map(|content| content.trim().to_string())
        .filter(|content| !content.is_empty())
        .ok_or_else(|| "provider returned an empty reply".to_string())?;

    Ok(reply)
}

fn truncate_for_log(text: &str, max_chars: usize) -> String {
    if text.chars().count() <= max_chars {
        return text.to_string();
    }
    let mut shortened: String = text.chars().take(max_chars).collect();
    shortened.push('…');
    shortened
}

